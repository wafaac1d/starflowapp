"""Календарная подпись знака по дате рождения.

Это не положение Солнца и не натальная карта. Границы — обычный тропический
календарь, который экран показывает как развлекательную подпись.
"""

from datetime import date

_STARTS: tuple[tuple[int, int, str], ...] = (
    (1, 20, "водолей"),
    (2, 19, "рыбы"),
    (3, 21, "овен"),
    (4, 20, "телец"),
    (5, 21, "близнецы"),
    (6, 21, "рак"),
    (7, 23, "лев"),
    (8, 23, "дева"),
    (9, 23, "весы"),
    (10, 23, "скорпион"),
    (11, 22, "стрелец"),
    (12, 22, "козерог"),
)


def calendar_sign(birth_date: date) -> str:
    chosen = "козерог"
    for month, day, name in _STARTS:
        if (birth_date.month, birth_date.day) >= (month, day):
            chosen = name
    return chosen
