import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(frontendRoot, "..");
const iconsDir = join(repoRoot, "static", "icons", "svg");
const names = readdirSync(iconsDir)
  .filter((file) => file.endsWith(".svg"))
  .map((file) => file.slice(0, -4))
  .sort();
const output = join(frontendRoot, "src", "shared", "ui", "Icon", "iconNames.ts");
const source = `/* generated by scripts/gen-icon-names.ts — do not edit */
export const iconNames = ${JSON.stringify(names, null, 2)} as const;

export type IconName = (typeof iconNames)[number];
`;
writeFileSync(output, source);
